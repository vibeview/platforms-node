// Generates src/generated/api.ts (the request and response types) and
// src/generated/error-codes.ts (the error codes the API documents) and
// src/generated/event-types.ts (the event types it documents) from openapi.json,
// the Partner API's OpenAPI document. Run `npm run generate` after replacing openapi.json.
//
// `render()` is also used by test/generated.test.ts, which fails when the committed files
// differ from what this script makes.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import * as prettier from 'prettier';

const root = new URL('../', import.meta.url);
export const SOURCE = new URL('openapi.json', root);
export const API_FILE = new URL('src/generated/api.ts', root);
export const ERROR_CODES_FILE = new URL('src/generated/error-codes.ts', root);
export const EVENT_TYPES_FILE = new URL('src/generated/event-types.ts', root);

const HEADER =
  '// Generated by scripts/generate.mjs from openapi.json. Do not edit: run `npm run generate`.\n';

async function format(source, file) {
  const options = (await prettier.resolveConfig(fileURLToPath(file))) ?? {};
  return prettier.format(source, { ...options, parser: 'typescript' });
}

function errorCodesSource(document) {
  const list = document.components?.schemas?.Error?.['x-vibeview-error-codes'];
  if (!Array.isArray(list) || list.length === 0) {
    throw new Error('openapi.json has no x-vibeview-error-codes on the Error schema');
  }
  const entries = [...list]
    .sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0))
    .map(
      ({ code, status, meaning }) =>
        `  ${JSON.stringify(code)}: { status: ${status === null ? 'null' : Number(status)}, meaning: ${JSON.stringify(meaning)} },`,
    );
  return [
    '/**',
    ' * The error codes the API documents today, each with its HTTP status (null when the',
    ' * code is sent with more than one status) and its meaning. The set is open: a newer',
    ' * API may send a code that is not listed here.',
    ' */',
    'export const ERROR_CODES = {',
    ...entries,
    '} as const satisfies Record<string, { status: number | null; meaning: string }>;',
    '',
    '/** A code listed in `ERROR_CODES`. */',
    'export type KnownErrorCode = keyof typeof ERROR_CODES;',
    '',
    '/** An `error.code`: a known code, or any other string a newer API sends. */',
    'export type ErrorCode = KnownErrorCode | (string & {});',
    '',
  ].join('\n');
}

function eventTypesSource(document) {
  const list = document.components?.schemas?.EventOut?.['x-vibeview-event-types'];
  if (!Array.isArray(list) || list.length === 0) {
    throw new Error('openapi.json has no x-vibeview-event-types on the EventOut schema');
  }
  const entries = [...list]
    .sort((a, b) => (a.type < b.type ? -1 : a.type > b.type ? 1 : 0))
    .map(({ type, sent }) => {
      if (typeof type !== 'string' || typeof sent !== 'boolean') {
        throw new Error('openapi.json has an x-vibeview-event-types entry without type and sent');
      }
      return `  ${JSON.stringify(type)}: { sent: ${sent} },`;
    });
  return [
    '/**',
    ' * The event types the API documented when this package version was built. `sent` is',
    ' * false for a type that was documented but not sent yet, as of this version: the API',
    ' * may start sending it later, so never use `sent` to drop events. The set is open: a',
    ' * newer API may send a type that is not listed here.',
    ' */',
    'export const EVENT_TYPES = {',
    ...entries,
    '} as const satisfies Record<string, { sent: boolean }>;',
    '',
    '/** A type listed in `EVENT_TYPES`. */',
    'export type KnownEventType = keyof typeof EVENT_TYPES;',
    '',
    '/** An event `type`: a known type, or any other string a newer API sends. */',
    'export type EventType = KnownEventType | (string & {});',
    '',
  ].join('\n');
}

/** The generated files' contents, formatted as they are committed. */
export async function render() {
  const document = JSON.parse(await readFile(SOURCE, 'utf8'));
  // A member with a default is optional (a request may leave it out), as the document says.
  const ast = await openapiTS(document, { defaultNonNullable: false, emptyObjectsUnknown: true });
  const api = await format(HEADER + '\n' + astToString(ast), API_FILE);
  const errorCodes = await format(HEADER + '\n' + errorCodesSource(document), ERROR_CODES_FILE);
  const eventTypes = await format(HEADER + '\n' + eventTypesSource(document), EVENT_TYPES_FILE);
  return { api, errorCodes, eventTypes };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { api, errorCodes, eventTypes } = await render();
  await writeFile(API_FILE, api);
  await writeFile(ERROR_CODES_FILE, errorCodes);
  await writeFile(EVENT_TYPES_FILE, eventTypes);
  console.log('Wrote src/generated/api.ts, error-codes.ts and event-types.ts');
}
